"""Generate ``docs/CURRENT_STATE.md`` — the canonical measured state of main
(prompt_evo_polish.md §18–§24, §79–§89).

Every field is *derived* from a live source — never maintained by hand:

- ``MAIN_SHA``           git rev-parse --short HEAD
- ``PACKAGE_VERSION``    sparkforge_azure.__version__
- ``TESTS``              the ``suite-green`` claim text in claims.lock.json
                         (the claim's *proof* reruns the suite — §86 forbids
                         running pytest inside this generator)
- ``CLAIMS``             claim count in docs/claims.lock.json
- ``SKILLS``             scripts/check_skills_agents.py JSON output
- ``AGENTS``             agents/*.md inventory
- ``MCP_TOOLS``          mcp.tools.load_all() catalog size
- ``CLI_COMMANDS``       docs/surface.lock.json command count
- ``PORTABILITY``        evals/portability report + static gate
- ``FREEZE``             agentic freeze evaluation
- ``REMOTE_CI``          declared constant — NOT_OBSERVED while GitHub quota
                         is exhausted (§75)

``--check`` regenerates in memory and fails on any *content* drift;
``MAIN_SHA``/timestamp differences are reported as informational only —
the doc records the SHA it was generated against, like a claim stamp.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

DOC = ROOT / "docs" / "CURRENT_STATE.md"
HEADER = "<!-- GENERATED by scripts/gen_current_state.py — do not hand-edit -->"
REMOTE_CI = "NOT_OBSERVED"


def _git(args: list[str]) -> str:
    proc = subprocess.run(
        ["git", *args], capture_output=True, text=True, cwd=str(ROOT)
    )
    return proc.stdout.strip() if proc.returncode == 0 else "unresolved"


def _suite_claim(claims: dict[str, object]) -> str:
    for claim in claims.get("claims", []):
        if claim.get("id") == "suite-green":
            return str(claim.get("text", "unresolved"))
    return "unresolved"


def _skills_count() -> int | str:
    proc = subprocess.run(
        [sys.executable, "scripts/check_skills_agents.py"],
        capture_output=True, text=True, cwd=str(ROOT),
    )
    try:
        return int(json.loads(proc.stdout)["skills"])
    except Exception:
        return "unresolved"


def _portability() -> str:
    report = ROOT / "evals" / "portability" / "reports" / "portability-matrix.json"
    if not report.is_file():
        return "unresolved"
    data = json.loads(report.read_text(encoding="utf-8"))
    results = data.get("results", [])
    ok = sum(1 for r in results if r.get("status") == "ok")
    return f"{ok}/{len(results)} cases ok" if results else "unresolved"


def _freeze() -> str:
    from sparkforge_azure.agentic.freeze import evaluate_freeze

    return str(evaluate_freeze(ROOT).get("freeze_status", "unresolved"))


def collect() -> dict[str, str]:
    from sparkforge_azure import __version__
    from sparkforge_azure.mcp.tools import load_all

    claims = json.loads(
        (ROOT / "docs" / "claims.lock.json").read_text(encoding="utf-8")
    )
    surface = json.loads(
        (ROOT / "docs" / "surface.lock.json").read_text(encoding="utf-8")
    )
    return {
        "MAIN_SHA": _git(["rev-parse", "--short", "HEAD"]),
        "PACKAGE_VERSION": __version__,
        "TESTS": _suite_claim(claims),
        "CLAIMS": str(len(claims.get("claims", []))),
        "SKILLS": str(_skills_count()),
        "AGENTS": str(len(list((ROOT / "agents").glob("*.md")))),
        "MCP_TOOLS": str(len(load_all())),
        "CLI_COMMANDS": str(len(surface.get("cli", {}).get("commands", []))),
        "PORTABILITY": _portability(),
        "FREEZE": _freeze(),
        "REMOTE_CI": REMOTE_CI,
    }


SOURCES = {
    "MAIN_SHA": "git rev-parse --short HEAD",
    "PACKAGE_VERSION": "sparkforge_azure.__version__",
    "TESTS": "claim `suite-green` em docs/claims.lock.json (prova = suite)",
    "CLAIMS": "docs/claims.lock.json",
    "SKILLS": "scripts/check_skills_agents.py",
    "AGENTS": "agents/*.md",
    "MCP_TOOLS": "sparkforge_azure.mcp.tools.load_all()",
    "CLI_COMMANDS": "docs/surface.lock.json",
    "PORTABILITY": "evals/portability/reports/portability-matrix.json",
    "FREEZE": "agentic.freeze.evaluate_freeze()",
    "REMOTE_CI": "constante declarada — quota GitHub esgotada",
}


def render(state: dict[str, str]) -> str:
    lines = [
        HEADER,
        "",
        "# CURRENT_STATE — estado medido da `main`",
        "",
        "Único documento voltado ao estado *atual* — outcome briefs preservam",
        "snapshots históricos de closure; aqui vive o número medido de agora.",
        "Paridade cross-Forge atual: seção *Post-closure freshness update* em",
        "`docs/portability/PORTABILITY_OUTCOME.md`.",
        "",
        "| Campo | Valor | Fonte |",
        "|---|---|---|",
    ]
    lines += [
        f"| {k} | `{v}` | {SOURCES[k]} |" for k, v in state.items()
    ]
    lines += [
        "",
        "Regenerar: `.venv/Scripts/python scripts/gen_current_state.py`",
        "Verificar drift: `... --check` (MAIN_SHA divergente = warn, não falha).",
        "",
    ]
    return "\n".join(lines)


def check() -> int:
    state = collect()
    if not DOC.is_file():
        print("current_state: doc missing — run gen_current_state.py")
        return 1
    def body_rows(text: str) -> list[str]:
        return [
            line for line in text.splitlines()
            if line.startswith("|") and "MAIN_SHA" not in line
        ]

    existing = DOC.read_text(encoding="utf-8")
    if body_rows(existing) != body_rows(render(state)):
        print("current_state: drift — regen with gen_current_state.py")
        return 1
    if state["MAIN_SHA"] not in existing:
        print(f"current_state: warn — doc stamped at a different SHA "
              f"(now {state['MAIN_SHA']})")
    print("current_state: ok")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        return check()
    state = collect()
    DOC.write_text(render(state), encoding="utf-8", newline="\n")
    print(f"current_state: written (sha {state['MAIN_SHA']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
