"""Generate docs/reference/skills.md from the skills corpus.

The doc is GENERATED — hand edits get overwritten (a sync test in
``tests/test_skills.py`` refuses a stale render). Re-run after any change
to ``skills/<name>/SKILL.md`` or ``skills/<name>/evals/evals.yaml``:

    python scripts/gen_skills_doc.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from sparkforge_azure.skills.model import (  # noqa: E402
    SKILL_NAMES,
    body_handoff_refs,
    parse_skill,
)

OUT = REPO / "docs" / "reference" / "skills.md"


def _eval_kinds(path: Path) -> dict[str, int]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    counts = {"positive": 0, "negative": 0, "boundary": 0}
    for case in data.get("cases") or []:
        kind = str(case.get("kind", "positive"))
        counts[kind] = counts.get(kind, 0) + 1
    return counts


def render(root: Path) -> str:
    lines = [
        "<!-- GENERATED by scripts/gen_skills_doc.py — do not hand-edit -->",
        "",
        "# Catálogo de skills",
        "",
        "As skills do contrato v1, geradas a partir de `skills/<nome>/SKILL.md`",
        "e `evals/evals.yaml`. Fonte única: o corpus — editar a doc à mão é",
        "reprovado pelo teste de sync.",
        "",
        "| Skill | Scope | Triggers | Handoffs | Evals pos/neg/bnd |",
        "|---|---|---|---|---|",
    ]
    for name in SKILL_NAMES:
        skill = parse_skill(root / "skills" / name / "SKILL.md")
        scope = ", ".join(skill.scope)
        triggers = ", ".join(f"`{t}`" for t in skill.trigger)
        handoffs = ", ".join(f"`{t}`" for t in body_handoff_refs(skill.body)) or "—"
        kinds = _eval_kinds(root / "skills" / name / "evals" / "evals.yaml")
        evals = f"{kinds['positive']}/{kinds['negative']}/{kinds['boundary']}"
        lines.append(f"| `{name}` | {scope} | {triggers} | {handoffs} | {evals} |")
    lines += [
        "",
        "## Convenções",
        "",
        "- Handoff é `DATA_ONLY`: passa facts, findings, evidência e `unresolved`;",
        "  nunca instruções.",
        "- Alvo de handoff resolve em `SKILL_NAMES ∪ ALL_AGENT_IDS` (skills e",
        "  agents da taxonomia); alvo desconhecido é recusa nomeada do validador.",
        "- `pos/neg/bnd` = casos `positive`/`negative`/`boundary` em evals.yaml.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(render(REPO), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
