"""Generate docs/agentic/AGENT_INVENTORY.md from the live inventory.

The doc is GENERATED — hand edits get overwritten. Re-run after any change
to agents/, the tool registry, or the inventory engine:

    python scripts/gen_agent_inventory.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from sparkforge_azure.agentic.inventory import inventory  # noqa: E402

OUT = REPO / "docs" / "agentic" / "AGENT_INVENTORY.md"


def main() -> int:
    rep = inventory(REPO)
    lines = [
        "<!-- GENERATED by scripts/gen_agent_inventory.py — do not hand-edit -->",
        "",
        "# Agent Inventory",
        "",
        "Per-agent contract status, measured by "
        "`sparkforge_azure.agentic.inventory` — a pure function of the "
        "repository tree. Status vocabulary (closed): `ready`, `partial`, "
        "`manifest_only`, `broken`, `unevaluated`.",
        "",
        "## Counts",
        "",
        "| status | agents |",
        "|---|---|",
    ]
    for status, n in sorted(rep.counts.items(), key=lambda kv: kv[0]):
        lines.append(f"| `{status}` | {n} |")
    lines += [
        "",
        f"**Total:** {len(rep.agents)} agents",
        "",
        "## Fleet",
        "",
        "| agent | kind | status |",
        "|---|---|---|",
    ]
    for a in rep.agents:
        lines.append(f"| `{a.agent_id}` | {a.kind} | `{a.status}` |")
    lines += [
        "",
        "## Dimensions",
        "",
        "Each agent is measured on: `manifest`, `role_plan`, `tool_policy`, "
        "`knowledge`, `budget`, `handoff`, `routing`, `evals`, `agentops`. "
        "A dimension reports `True` (measured pass), `False` (measured fail), "
        "or `null` — not measurable, unresolved. Inspect one agent:",
        "",
        "```bash",
        "sparkforge-azure agents inspect <id>",
        "```",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
