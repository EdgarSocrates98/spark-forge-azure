"""Generate docs/reference/agents.md from the agent manifest corpus.

The doc is GENERATED — hand edits get overwritten (a sync test in
``tests/test_agents_doc.py`` refuses a stale render). Re-run after any
change to ``agents/<id>.md``:

    python scripts/gen_agents_doc.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from sparkforge_azure.agentmanifest.model import (  # noqa: E402
    ALL_AGENT_IDS,
    parse_manifest,
)

OUT = REPO / "docs" / "reference" / "agents.md"

_KIND_ORDER = {"role": 0, "specialist": 1, "subagent": 2}


def render(root: Path) -> str:
    lines = [
        "<!-- GENERATED by scripts/gen_agents_doc.py — do not hand-edit -->",
        "",
        "# Catálogo de agents",
        "",
        "Os 40 agents do contrato v2, gerados a partir de `agents/<id>.md`.",
        "Fonte única: os manifests — editar a doc à mão é reprovado pelo",
        "teste de sync.",
        "",
        "| Agent | Kind | Domain | Autonomy | Risk | Evals |",
        "|---|---|---|---|---|---|",
    ]
    rows = []
    for agent_id in ALL_AGENT_IDS:
        data = parse_manifest(root / "agents" / f"{agent_id}.md").data
        rows.append((
            _KIND_ORDER.get(str(data.get("kind")), 9),
            agent_id,
            str(data.get("kind")),
            str(data.get("domain") or "—"),
            str(data.get("autonomy") or "—"),
            str(data.get("risk") or "—"),
            len(data.get("evals") or []),
        ))
    for _, agent_id, kind, domain, autonomy, risk, n_evals in sorted(rows):
        lines.append(
            f"| `{agent_id}` | {kind} | {domain} | {autonomy} | "
            f"{risk} | {n_evals} |"
        )
    lines += [
        "",
        "## Convenções",
        "",
        "- `autonomy` é o nível L0–L5 do contrato v2 (§153): a frota inteira",
        "  fica ≤ L2 — L4/L5 exigem exceção revisada, nunca são default.",
        "- `evals` conta refs que resolvem em `tests/`/`evals/` — ref",
        "  inexistente reprova o inventário (`unresolvable`).",
        "- Reviewers e subagents são spawn-only: nunca entram na",
        "  `ROUTING_TABLE` top-level.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    OUT.write_text(render(REPO), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
